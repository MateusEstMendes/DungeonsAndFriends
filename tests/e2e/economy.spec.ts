import { test, expect } from './fixtures';
import { readFileSync } from 'node:fs';
test.use({ actionTimeout: 20_000 });
test('mochila, baú, loja, pergaminho, dados e chat de sete segundos', async ({ browser }) => {
  test.setTimeout(240_000);
  const gmContext = await browser.newContext({ reducedMotion: 'reduce' }), context = await browser.newContext({ viewport: { width: 1280, height: 844 }, reducedMotion: 'reduce' });
  const gm = await gmContext.newPage(), player = await context.newPage(), errors: string[] = [];
  for (const page of [gm, player]) page.on('pageerror', e => errors.push(e.message));
  const fixture = JSON.parse(readFileSync('.local/e2e-player.json', 'utf8'));
  try {
    await gm.goto('/'); await gm.getByText('Acesso do Mestre', { exact: true }).click();
    await gm.getByLabel('Senha do Mestre').fill('board-e2e-password'); await gm.getByRole('button', { name: 'Entrar como Mestre' }).click();
    await gm.getByRole('combobox', { name: 'Ritmo da aventura' }).selectOption('FREE_EXPLORATION');
    await context.addInitScript(data => { if (location.protocol !== 'http:') return; localStorage.setItem('df_session_token', data.token); localStorage.setItem('df_room_code', data.roomCode); localStorage.setItem('df_player_name', data.name); }, fixture);
    await player.goto('/'); await player.getByRole('button', { name: 'Continuar sessão' }).click();
    await expect(player.getByRole('region', { name: 'Seu personagem', exact: true })).toBeVisible();
    await player.getByText('Mover por coordenadas', { exact: true }).click();
    const form = player.locator('.vitals-hud .coordinate-form');
    await form.getByLabel('q', { exact: true }).fill('0'); await form.getByLabel('r', { exact: true }).fill('0');
    await form.getByRole('button', { name: 'Mover', exact: true }).click();
    await expect(player.getByText('Hexágono (0, 0)', { exact: true })).toBeVisible();
    await player.setViewportSize({ width: 390, height: 844 });
    await player.getByRole('button', { name: '🧰 Abrir Baú', exact: true }).click();
    const chest = player.getByRole('dialog', { name: 'Baú compartilhado' });
    await expect(chest).toContainText('Espada Grande ×1');
    await chest.getByRole('button', { name: 'Coletar tudo', exact: true }).click();
    await expect(chest).toContainText('Baú vazio.'); await player.getByRole('button', { name: 'Fechar janela' }).click();
    await player.getByRole('button', { name: '🎒 Ficha', exact: true }).click();
    const sheet = player.getByRole('dialog', { name: 'Ael de Teste', exact: true });
    await sheet.getByRole('button', { name: 'Equipamentos & Mochila', exact: true }).click();
    await sheet.locator('article').filter({ has: player.getByText('Escudo de Madeira ×1', { exact: true }) }).getByRole('button', { name: 'Equipar secundária', exact: true }).click();
    await expect(sheet.getByRole('button', { name: 'Desequipar Mão Secundária' })).toBeEnabled();
    await sheet.locator('article').filter({ has: player.getByText('Espada Grande ×1', { exact: true }) }).getByRole('button', { name: 'Equipar principal', exact: true }).click();
    await expect(sheet).toContainText('Ocupada por arma de duas mãos');
    await expect(sheet.getByRole('button', { name: 'Desequipar Mão Secundária' })).toHaveCount(0);
    await sheet.getByRole('button', { name: 'Grimório', exact: true }).click();
    const read = sheet.getByRole('button', { name: 'Ler Pergaminho de Explosão Ígnea', exact: true });
    // A previous combat test may already have learned it; otherwise learn through the real UI.
    if (await read.isEnabled()) await read.click();
    await expect(sheet).toContainText('Explosão Ígnea · 10 MP');
    await player.keyboard.press('Escape');
    await player.getByRole('button', { name: '💬 Comerciar', exact: true }).click();
    const shop = player.getByRole('dialog', { name: 'Mercador de teste' });
    const before = Number((await shop.locator('.gold-balance').innerText()).replace(' G', ''));
    await shop.getByRole('button', { name: 'Comprar Adaga', exact: true }).click();
    await expect(shop.locator('.gold-balance')).toHaveText(`${before - 40} G`);
    await shop.getByRole('button', { name: 'Vender (50%)', exact: true }).click();
    await expect(shop.getByRole('button', { name: 'Vender Espada Grande' })).toBeDisabled();
    await shop.getByRole('button', { name: 'Vender Adaga', exact: true }).click();
    await expect(shop.locator('.gold-balance')).toHaveText(`${before - 20} G`);
    await player.getByRole('button', { name: 'Fechar janela' }).click();
    await gm.getByRole('button', { name: 'Selecionar', exact: true }).click();
    const canvas = gm.locator('.board-canvas canvas'), box = (await canvas.boundingBox())!;
    const scale = Math.min(1, box.width / 850, box.height / 730);
    await canvas.click({ position: { x: box.width / 2 + Math.sqrt(3) * 20 * scale, y: box.height / 2 + 60 * scale } });
    await gm.getByRole('combobox', { name: 'Entidades neste hexágono' }).selectOption('economy-shop');
    await gm.getByRole('button', { name: 'Editar Loja', exact: true }).click();
    const masterShop = gm.getByRole('dialog', { name: 'Mercador de teste' });
    await masterShop.getByRole('button', { name: 'Editar Loja', exact: true }).click();
    await masterShop.getByLabel('Diálogo', { exact: true }).fill('Mercadorias para a próxima aventura.');
    await masterShop.getByRole('button', { name: 'Salvar loja', exact: true }).click();
    await expect(masterShop).toContainText('Mercadorias para a próxima aventura.');
    await gm.getByRole('button', { name: 'Fechar janela' }).click();
    await player.getByRole('button', { name: '💬 Comerciar', exact: true }).click();
    await expect(shop).toContainText('Mercadorias para a próxima aventura.');
    await player.getByRole('button', { name: 'Fechar janela' }).click();
    await player.getByRole('button', { name: '🎲 Dados', exact: true }).click();
    await player.getByRole('button', { name: 'd20', exact: true }).click();
    await expect(player.getByRole('dialog', { name: 'Bandeja de dados' })).toContainText(/d20: \d+/);
    await player.getByRole('button', { name: 'Fechar janela' }).click();
    await gm.getByRole('button', { name: '📜 Log', exact: true }).click();
    await expect(gm.getByRole('dialog', { name: 'Log da aventura' })).toContainText(/d20: \d+/);
    await gm.getByRole('button', { name: 'Fechar janela' }).click();
    await player.getByText('Chat da câmara', { exact: true }).click();
    await player.getByRole('textbox', { name: 'Mensagem na câmara' }).fill('Olá da mochila!');
    await player.getByRole('button', { name: 'Enviar', exact: true }).click();
    // The board bubble is drawn by Pixi; inspect the received socket and expiration via the arena toast in combat.
    await gm.getByRole('button', { name: 'Iniciar Combate', exact: true }).click();
    await player.getByRole('textbox', { name: 'Mensagem na câmara' }).fill('Chat na arena');
    await player.getByRole('button', { name: 'Enviar', exact: true }).click();
    await expect(gm.locator('.ephemeral-chat')).toContainText('Chat na arena');
    await expect(gm.locator('.ephemeral-chat')).not.toContainText('Chat na arena', { timeout: 10_000 });
    await gm.getByRole('button', { name: 'Encerrar combate', exact: true }).click();
    await player.screenshot({ timeout: 60_000, path: '.local/phase5-economy-mobile.png' });
    expect(await player.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(errors).toEqual([]);
    await player.getByRole('button', { name: 'Sair', exact: true }).click(); await gm.getByRole('button', { name: 'Sair', exact: true }).click();
  } finally { await context.close(); await gmContext.close(); }
});
