import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('Mestre observa herói, comanda criatura e identifica impacto no jogador', async ({ browser }) => {
  test.setTimeout(180_000);
  const gmContext = await browser.newContext(), gm = await gmContext.newPage();
  const errors: string[] = []; gm.on('pageerror', e => errors.push(e.message));
  await gm.goto('/'); await gm.getByText('Acesso do Mestre', { exact: true }).click();
  await gm.getByLabel('Senha do Mestre').fill('board-e2e-password'); await gm.getByRole('button', { name: 'Entrar como Mestre' }).click();
  await gm.getByRole('combobox', { name: 'Ritmo da aventura' }).selectOption('FREE_EXPLORATION');
  await gm.getByRole('combobox', { name: 'Bioma da câmara' }).selectOption('FOREST');
  await expect(gm.getByRole('combobox', { name: 'Bioma da câmara' })).toHaveValue('FOREST');
  const fixture = JSON.parse(readFileSync('.local/e2e-player.json', 'utf8'));
  const context = await browser.newContext({ viewport: { width: 1280, height: 720 }, isMobile: true, hasTouch: true });
  await context.addInitScript(data => {
    if (location.protocol !== 'http:' && location.protocol !== 'https:') return;
    localStorage.setItem('df_session_token', data.token); localStorage.setItem('df_room_code', data.roomCode); localStorage.setItem('df_player_name', data.name);
  }, fixture);
  const player = await context.newPage(); player.on('pageerror', e => errors.push(e.message));
  await player.goto('/'); await player.getByRole('button', { name: 'Continuar sessão' }).click();
  await player.getByText('Mover por coordenadas', { exact: true }).click();
  const form = player.locator('.vitals-hud .coordinate-form');
  await form.getByLabel('q', { exact: true }).fill('3'); await form.getByLabel('r', { exact: true }).fill('-1');
  await form.getByRole('button', { name: 'Mover', exact: true }).click();
  await expect(gm.getByText('[Inimigo próximo! Iniciar Combate]', { exact: true })).toBeVisible();
  await player.setViewportSize({ width: 390, height: 844 });
  await gm.getByRole('button', { name: 'Iniciar Combate', exact: true }).click();
  await expect(player.getByRole('region', { name: 'Arena de combate', exact: true })).toBeVisible();
  await expect(gm.getByRole('region', { name: 'Arena de combate', exact: true })).toBeVisible();
  await expect(player.locator('.combat-heading')).toContainText('Floresta');
  await expect(player.locator('.board-canvas canvas')).toHaveAttribute('aria-label', /Arena de combate/);
  await expect(player.getByRole('button', { name: 'Atacar', exact: true })).toBeEnabled();
  await expect(gm.locator('.combat-heading')).toContainText('Observando turno de Ael de Teste');
  await expect(gm.getByRole('navigation', { name: 'Ações de combate' })).toHaveCount(0);
  await player.getByRole('button', { name: 'Atacar', exact: true }).click();
  await player.getByRole('button', { name: 'Desarmado', exact: true }).click();
  await expect(player.locator('.active-portrait')).toContainText('1 ação(ões)');
  await expect(player.getByRole('button', { name: 'Fugir', exact: true })).toBeDisabled();
  await expect(player.locator('.combat-dice-status span')).toContainText('d20:');
  const firstNatural = Number((await player.locator('.combat-dice-status span').innerText()).match(/d20: (\d+)/)?.[1]);
  await expect(player.locator('.combat-dice-status strong')).toContainText(firstNatural + 5 < 10 ? 'Errou: defesa do alvo' : 'DR absorveu');
  const result = await player.locator('.combat-dice-status').innerText();
  await expect(gm.locator('.combat-dice-status')).toHaveText(result.replace(/\n/g, ''));
  await player.screenshot({ path: '.local/phase4-player-mobile.png' });
  expect(await player.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await player.getByRole('button', { name: 'Defender', exact: true }).click();
  await player.getByRole('button', { name: 'Esquiva Ativa', exact: true }).click();
  await gm.getByText('Controlar monstro', { exact: true }).click();
  await gm.getByRole('button', { name: /^Goblin · Manual/ }).click();
  await expect(gm.locator('.combat-heading')).toContainText('Controlando: Goblin');
  await gm.getByRole('button', { name: 'Atacar', exact: true }).click();
  await expect(gm.getByRole('button', { name: 'Fogo', exact: true })).toHaveCount(0);
  await expect(gm.getByRole('button', { name: 'Corte', exact: true })).toHaveCount(0);
  await gm.getByRole('button', { name: 'Perfuração', exact: true }).click();
  await expect(player.locator('.combat-dice-status p')).toHaveText('Monstro Goblin ataca Ael de Teste');
  await expect(gm.locator('.combat-dice-status p')).toHaveText('Monstro Goblin ataca Ael de Teste');
  await expect(player.locator('.combat-ally').filter({ hasText: 'Ael de Teste' })).toContainText('HP');
  await gm.getByRole('button', { name: 'Encerrar combate', exact: true }).click();
  expect(errors).toEqual([]);
  await context.close(); await gmContext.close();
});
